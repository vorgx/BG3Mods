"""Build the local 'ModCheck Loot Merge' pak from config/loot_merge.json.

Some mods replace a loot table outright when they meant to add to it, or two mods each replace the same table with
their own additions. This writes one pak that redefines those tables with everyone's items, to load after all of them.

  python build_lootpatch.py            build work/lootpatch/ModCheck_LootMerge.pak and print what it contains
"""
import json, os, re, shutil, subprocess, sys, uuid
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bg3lib as L

FOLDER = "ModCheck_LootMerge"
NAME = "ModCheck Loot Merge"
UUID = "6d0c8f3e-4b1a-4f5e-9c2d-8a7b3e1f0c55"  # fixed, so rebuilds replace the same mod in the load order
DIVINE = os.path.join(L.PROJECT, "LsLib", "Tools", "Divine.exe")
cfg = json.load(open(os.path.join(L.CONF, "loot_merge.json"), encoding="utf-8"))
lo = L.load("lo_report.json")
order = [m["pak"] for m in lo["current"]]
uuid_of = {m["pak"]: m["uuid"] for m in lo["current"]}
name_of = {m["pak"]: m["name"] for m in lo["current"]}


def tables(pak):
    out = {}
    with open(os.path.join(L.MODS, pak), "rb") as f:
        for e in L.pak_entries(f):
            if L.STATS_RE.match(e[0]):
                t = (L.pak_read(f, e) or b"").decode("utf-8", "replace")
                for m in re.finditer(r'new treasuretable\s+"([^"]+)"(.*?)(?=\nnew treasuretable|\Z)', t, re.S):
                    out[m.group(1)] = m.group(2)
    return out


def subtables(body):
    """[(header, [object lines])] with comments and CanMerge dropped."""
    out = []
    for line in body.split("\n"):
        s = line.strip()
        if not s or s.startswith("//") or s.startswith("#") or s.startswith("CanMerge"):
            continue
        if s.startswith("new subtable"):
            out.append((s, []))
        elif s.startswith("object category") and out:
            out[-1][1].append(s)
    return out


def render(name, subs):
    lines = [f'new treasuretable "{name}"']
    for head, objs in subs:
        lines.append(head)
        lines += objs
    return "\n".join(lines) + "\n"


cache = {}


def T(pak):
    if pak not in cache:
        try:
            cache[pak] = tables(pak)
        except Exception as ex:  # missing or damaged pak: it can't contribute loot anyway
            print(f"[WARN] {pak}: {type(ex).__name__}; skipped")
            cache[pak] = {}
    return cache[pak]


out_tables, report, deps = {}, [], set()
for rule in cfg.get("pools", []):
    base, add, minus = T(rule["base"]), T(rule["add_from"]), T(rule["minus_base"])
    names = sorted(set(base) & set(add)) if rule["tables"] == "shared" else rule["tables"]
    deps |= {rule["base"], rule["add_from"], rule["minus_base"]}
    for n in names:
        subs = subtables(base[n])
        if len(subs) != 1:
            print(f"[WARN] {n}: expected one list, found {len(subs)} subtables; skipped")
            continue
        have = {re.search(r'"([^"]+)"', o).group(1) for o in subs[0][1]}
        base_orig = {re.search(r'"([^"]+)"', o).group(1) for s in subtables(minus.get(n, "")) for o in s[1]}
        extra = [o for s in subtables(add[n]) for o in s[1] if re.search(r'"([^"]+)"', o).group(1) not in have | base_orig]
        out_tables[n] = render(n, [(subs[0][0], subs[0][1] + extra)])
        report.append((n, len(subs[0][1]), len(extra)))

for rule in cfg.get("subtables", []):
    n = rule["table"]
    definers = [pk for pk in order if n in T(pk)] if all(pk in order for pk in [rule["base"]]) else []
    start = definers.index(rule["base"]) if rule["base"] in definers else None
    if start is None:
        print(f"[WARN] {n}: base {rule['base']} doesn't define it; skipped")
        continue
    subs, seen = [], set()
    for pk in definers[start:]:
        body = T(pk)[n]
        if pk != rule["base"] and not re.search(r"CanMerge\s+1", body) and pk not in rule.get("treat_as_merge", []):
            print(f"[WARN] {n}: {pk} replaces it and isn't listed as a merge; its entries are included anyway")
        for s in subtables(body):
            key = (s[0], tuple(s[1]))
            if key not in seen:
                seen.add(key)
                subs.append(s)
        deps.add(pk)
    out_tables[n] = render(n, subs)
    report.append((n, len(subs), [name_of.get(pk, pk) for pk in definers[start:]]))

# ---------- write the mod folder and pack it
root = os.path.join(L.WORK, "lootpatch")
shutil.rmtree(root, ignore_errors=True)
src = os.path.join(root, "src")
os.makedirs(os.path.join(src, "Mods", FOLDER))
os.makedirs(os.path.join(src, "Public", FOLDER, "Stats", "Generated"))
header = "// Generated by Scripts/ModUpdateCheck/build_lootpatch.py from config/loot_merge.json. Rebuild instead of editing.\n\n"
open(os.path.join(src, "Public", FOLDER, "Stats", "Generated", "TreasureTable.txt"), "w", encoding="utf-8", newline="\r\n").write(
    header + "\n".join(out_tables[n] for n in sorted(out_tables)))
version64 = str((1 << 55) | (1 << 31) * 0)  # 1.0.0.0
dep_xml = "".join(
    f'\n          <node id="ModuleShortDesc">\n            <attribute id="Folder" type="LSString" value="{d["folder"]}" />'
    f'\n            <attribute id="MD5" type="LSString" value="" />\n            <attribute id="Name" type="LSString" value="{d["name"]}" />'
    f'\n            <attribute id="PublishHandle" type="uint64" value="0" />\n            <attribute id="UUID" type="guid" value="{d["uuid"]}" />'
    f'\n            <attribute id="Version64" type="int64" value="0" />\n          </node>'
    for d in [L.scan_pak(os.path.join(L.MODS, pk), want_stats=False) for pk in sorted(deps, key=order.index)])
meta = f'''<?xml version="1.0" encoding="utf-8"?>
<save>
  <version major="4" minor="0" revision="9" build="331" />
  <region id="Config">
    <node id="root">
      <children>
        <node id="Dependencies">
          <children>{dep_xml}
          </children>
        </node>
        <node id="ModuleInfo">
          <attribute id="Author" type="LSWString" value="ModCheck (generated locally)" />
          <attribute id="CharacterCreationLevelName" type="FixedString" value="" />
          <attribute id="Description" type="LSWString" value="Merges loot tables that other mods replace instead of extending. Built from config/loot_merge.json." />
          <attribute id="Folder" type="LSWString" value="{FOLDER}" />
          <attribute id="LobbyLevelName" type="FixedString" value="" />
          <attribute id="MD5" type="LSString" value="" />
          <attribute id="MenuLevelName" type="FixedString" value="" />
          <attribute id="Name" type="FixedString" value="{NAME}" />
          <attribute id="NumPlayers" type="uint8" value="4" />
          <attribute id="PhotoBooth" type="FixedString" value="" />
          <attribute id="StartupLevelName" type="FixedString" value="" />
          <attribute id="Tags" type="LSWString" value="" />
          <attribute id="Type" type="FixedString" value="Add-on" />
          <attribute id="UUID" type="FixedString" value="{UUID}" />
          <attribute id="Version64" type="int64" value="{version64}" />
          <children>
            <node id="PublishVersion">
              <attribute id="Version64" type="int64" value="{version64}" />
            </node>
          </children>
        </node>
      </children>
    </node>
  </region>
</save>
'''
open(os.path.join(src, "Mods", FOLDER, "meta.lsx"), "w", encoding="utf-8").write(meta)
pak = os.path.join(root, f"{FOLDER}.pak")
r = subprocess.run([DIVINE, "-g", "bg3", "-a", "create-package", "-s", os.path.abspath(src), "-d", os.path.abspath(pak), "-c", "lz4"],
                   capture_output=True, text=True)
if r.returncode or not os.path.exists(pak):
    sys.exit(f"[FAIL] Divine could not pack the patch: {(r.stdout + r.stderr)[-400:]}")

# ---------- verify by reading the pak back
check = L.scan_pak(pak)
back = tables_from = {}
with open(pak, "rb") as f:
    for e in L.pak_entries(f):
        if L.STATS_RE.match(e[0]):
            back = {m.group(1) for m in re.finditer(r'new treasuretable\s+"([^"]+)"', L.pak_read(f, e).decode("utf-8"))}
assert check.get("uuid") == UUID and back == set(out_tables), "packed patch doesn't read back correctly"
for n, a, b in report:
    if isinstance(b, int):
        print(f"[INFO] {n}: {a} AMP Plus items + {b} FED items")
    else:
        print(f"[INFO] {n}: {a} drop groups from {', '.join(b)}")
print(f"[PASS] Built {pak} ({len(out_tables)} tables, depends on {len(deps)} mods)")

# ---------- --install: copy into Mods (old copy backed up); enable it with fix_order.py --enable
if "--install" in sys.argv:
    if L.bg3_running():
        sys.exit("[FAIL] Baldur's Gate 3 is running. Close it first.")
    bdir = L.new_backup_dir("lootpatch")
    L.backup_modsettings(bdir)
    dest = os.path.join(L.MODS, f"{FOLDER}.pak")
    if os.path.exists(dest):
        os.makedirs(os.path.join(bdir, "paks"), exist_ok=True)
        shutil.move(dest, os.path.join(bdir, "paks", f"{FOLDER}.pak"))
        L.record_moved_pak(bdir, dest, os.path.join(bdir, "paks", f"{FOLDER}.pak"), dest)
    else:
        L.record_added_pak(bdir, dest)
    shutil.copy2(pak, dest)
    print(f"[PASS] Installed {dest}. Backup: {bdir}")
